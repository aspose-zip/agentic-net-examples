// HOW-TO: Add Files to Existing ZIP Archive from Streams in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded paths
            string sourceArchivePath = "data\\source.zip";
            string inputFile1 = "data\\file1.txt";
            string inputFile2 = "data\\file2.txt";
            string resultArchivePath = "output\\result.zip";

            // Validate input files
            if (!File.Exists(sourceArchivePath))
            {
                Console.Error.WriteLine($"File not found: {sourceArchivePath}");
                return;
            }
            if (!File.Exists(inputFile1))
            {
                Console.Error.WriteLine($"File not found: {inputFile1}");
                return;
            }
            if (!File.Exists(inputFile2))
            {
                Console.Error.WriteLine($"File not found: {inputFile2}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(resultArchivePath));

            // Open source files for reading
            using (FileStream stream1 = File.OpenRead(inputFile1))
            using (FileStream stream2 = File.OpenRead(inputFile2))
            // Open existing archive
            using (Archive archive = new Archive(sourceArchivePath))
            {
                // Add entries from opened streams
                archive.CreateEntry("file1.txt", stream1);
                archive.CreateEntry("file2.txt", stream2);

                // Save the modified archive
                archive.Save(resultArchivePath);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

