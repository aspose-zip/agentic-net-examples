// HOW-TO: Compress Extracted Image Files into a ZIP Archive Using C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Linq;
using System.Text;
using Aspose.Zip;
using Aspose.Zip.Saving;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input directory containing extracted images
            string inputDirectory = @"C:\Temp\ExtractedImages";
            // Hardcoded output ZIP file path
            string outputZipPath = @"C:\Temp\ExtractedImages.zip";

            // Verify input directory exists
            if (!Directory.Exists(inputDirectory))
            {
                Console.Error.WriteLine($"Directory not found: {inputDirectory}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputZipPath));

            // Define image file extensions to include
            string[] imageExtensions = new string[] { ".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tiff" };

            // Collect all image files from the input directory
            IEnumerable<string> imageFiles = Directory.GetFiles(inputDirectory)
                .Where(file => imageExtensions.Contains(Path.GetExtension(file), StringComparer.OrdinalIgnoreCase));

            // Create the ZIP archive and add each image file as an entry
            using (FileStream zipStream = File.Open(outputZipPath, FileMode.Create))
            using (Archive archive = new Archive())
            {
                foreach (string imagePath in imageFiles)
                {
                    // Verify each image file exists before adding
                    if (!File.Exists(imagePath))
                    {
                        Console.Error.WriteLine($"File not found: {imagePath}");
                        continue;
                    }

                    using (FileStream sourceStream = File.Open(imagePath, FileMode.Open, FileAccess.Read))
                    {
                        string entryName = Path.GetFileName(imagePath);
                        archive.CreateEntry(entryName, sourceStream);
                    }
                }

                // Set optional save options (e.g., encoding and comment)
                ArchiveSaveOptions saveOptions = new ArchiveSaveOptions();
                saveOptions.Encoding = Encoding.UTF8;
                saveOptions.ArchiveComment = "Compressed extracted images";

                // Save the archive to the output ZIP file
                archive.Save(zipStream, saveOptions);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

