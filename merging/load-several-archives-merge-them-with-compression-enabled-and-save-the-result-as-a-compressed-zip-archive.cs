// HOW-TO: Merge Multiple ZIP Files into a Single Compressed Archive in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Collections.Generic;
using Aspose.Zip;
using Aspose.Zip.Saving;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input archive paths
            string inputPath1 = "archive1.zip";
            string inputPath2 = "archive2.zip";
            string inputPath3 = "archive3.zip";

            // Hardcoded output archive path
            string outputPath = "merged.zip";

            // Validate input files
            if (!File.Exists(inputPath1))
            {
                Console.Error.WriteLine($"File not found: {inputPath1}");
                return;
            }
            if (!File.Exists(inputPath2))
            {
                Console.Error.WriteLine($"File not found: {inputPath2}");
                return;
            }
            if (!File.Exists(inputPath3))
            {
                Console.Error.WriteLine($"File not found: {inputPath3}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // List of input archives
            List<string> inputArchives = new List<string> { inputPath1, inputPath2, inputPath3 };

            // Create the resulting archive
            using (Archive resultArchive = new Archive())
            {
                // Iterate over each source archive
                foreach (string srcPath in inputArchives)
                {
                    using (Archive srcArchive = new Archive(srcPath))
                    {
                        // Copy each entry from source to result archive
                        foreach (ArchiveEntry srcEntry in srcArchive.Entries)
                        {
                            using (Stream srcStream = srcEntry.Open())
                            {
                                MemoryStream entryData = new MemoryStream();
                                srcStream.CopyTo(entryData);
                                entryData.Position = 0;

                                // Add entry to result archive (default compression is enabled)
                                resultArchive.CreateEntry(srcEntry.Name, entryData);
                            }
                        }
                    }
                }

                // Save the merged archive to the output file
                using (FileStream outStream = File.Open(outputPath, FileMode.Create))
                {
                    resultArchive.Save(outStream, new ArchiveSaveOptions());
                }
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

