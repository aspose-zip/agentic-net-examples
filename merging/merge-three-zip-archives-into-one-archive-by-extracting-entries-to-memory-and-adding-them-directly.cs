// HOW-TO: Merge Multiple ZIP Files into a Single Archive Using Memory Streams in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Collections.Generic;
using Aspose.Zip;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath1 = @"C:\Data\archive1.zip";
            string inputPath2 = @"C:\Data\archive2.zip";
            string inputPath3 = @"C:\Data\archive3.zip";
            string outputPath = @"C:\Data\merged.zip";

            // Validate input files
            if (!File.Exists(inputPath1))
            {
                Console.Error.WriteLine($"File not found: {inputPath1}");
                return;
            }
            if (!File.Exists(inputPath2))
            {
                Console.Error.WriteLine($"File not found: {inputPath2}");
                return;
            }
            if (!File.Exists(inputPath3))
            {
                Console.Error.WriteLine($"File not found: {inputPath3}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // List of source archive paths
            List<string> sourcePaths = new List<string> { inputPath1, inputPath2, inputPath3 };

            // Keep memory streams alive until the merged archive is saved
            List<MemoryStream> tempStreams = new List<MemoryStream>();

            using (Archive mergedArchive = new Archive())
            {
                foreach (string srcPath in sourcePaths)
                {
                    using (Archive srcArchive = new Archive(srcPath))
                    {
                        foreach (ArchiveEntry entry in srcArchive.Entries)
                        {
                            using (Stream entryStream = entry.Open())
                            {
                                MemoryStream ms = new MemoryStream();
                                entryStream.CopyTo(ms);
                                ms.Position = 0;

                                // Add entry to the merged archive
                                mergedArchive.CreateEntry(entry.Name, ms);
                                tempStreams.Add(ms);
                            }
                        }
                    }
                }

                // Save the merged archive
                mergedArchive.Save(outputPath);
            }

            // Dispose temporary memory streams
            foreach (MemoryStream ms in tempStreams)
            {
                ms.Dispose();
            }

            Console.WriteLine("Archives merged successfully.");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

