// HOW-TO: Merge Multiple Large ZIP Files In-Memory With Collision Handling C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Collections.Generic;
using Aspose.Zip;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input ZIP archive paths
            string[] sourcePaths = new string[]
            {
                @"C:\Data\archive1.zip",
                @"C:\Data\archive2.zip",
                @"C:\Data\archive3.zip"
            };

            // Hardcoded output path
            string outputPath = @"C:\Data\merged.zip";

            // Verify each source archive exists
            foreach (string src in sourcePaths)
            {
                if (!File.Exists(src))
                {
                    Console.Error.WriteLine($"File not found: {src}");
                    return;
                }
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Set to track entry names and resolve collisions
            HashSet<string> existingNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            // Create a new empty archive for the merged result
            using (Archive mergedArchive = new Archive())
            {
                foreach (string srcPath in sourcePaths)
                {
                    using (Archive srcArchive = new Archive(srcPath))
                    {
                        foreach (ArchiveEntry entry in srcArchive.Entries)
                        {
                            // Original entry name
                            string originalName = entry.Name;

                            // Resolve name collisions
                            string uniqueName = originalName;
                            int duplicateIndex = 1;
                            while (existingNames.Contains(uniqueName))
                            {
                                string nameWithoutExt = Path.GetFileNameWithoutExtension(originalName);
                                string ext = Path.GetExtension(originalName);
                                uniqueName = $"{nameWithoutExt}_dup{duplicateIndex}{ext}";
                                duplicateIndex++;
                            }
                            existingNames.Add(uniqueName);

                            // Load entry data into memory and add to merged archive
                            using (MemoryStream ms = new MemoryStream())
                            {
                                using (Stream entryStream = entry.Open())
                                {
                                    entryStream.CopyTo(ms);
                                }
                                ms.Position = 0;
                                mergedArchive.CreateEntry(uniqueName, ms);
                            }
                        }
                    }
                }

                // Save the merged archive
                mergedArchive.Save(outputPath);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

