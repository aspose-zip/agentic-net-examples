// HOW-TO: Extract ALZ Archive to Folder in C# Using Aspose.Zip (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip;

public class Program
{
    public static void Main(string[] args)
    {
        try
        {
            // Hardcoded input ALZ archive path
            string inputPath = @"C:\Archives\sample.alz";

            // Verify that the input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Hardcoded output directory path
            string outputPath = @"C:\ExtractedAlz";

            // Ensure the output directory exists
            Directory.CreateDirectory(outputPath);

            // Open the ALZ archive and extract all entries
            using (IArchive archive = ArchiveFactory.GetArchive(inputPath))
            {
                archive.ExtractToDirectory(outputPath);
            }

            Console.WriteLine("Extraction completed successfully.");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

