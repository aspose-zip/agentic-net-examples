// HOW-TO: Extract Single File From XZ Archive And Log Byte Count In C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Xz;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath = @"C:\Data\image_archive.xz";
            string outputPath = @"C:\Data\image_recovered.bin";
            string reportPath = @"C:\Data\report.txt";

            // Validate input file existence
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure output directories exist
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));
            Directory.CreateDirectory(Path.GetDirectoryName(reportPath));

            // Decompress the XZ archive to a file
            using (XzArchive archive = new XzArchive(inputPath))
            using (FileStream outputStream = File.Create(outputPath))
            {
                archive.Extract(outputStream);
                // Get the number of bytes written
                long recoveredByteCount = outputStream.Position;

                // Write a text report with the byte count
                using (StreamWriter writer = new StreamWriter(reportPath, false))
                {
                    writer.WriteLine($"Recovered byte count: {recoveredByteCount}");
                }
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

