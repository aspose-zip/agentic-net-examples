// HOW-TO: Decompress XZ Archive and Generate Byte Count Report in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Xz;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath = "data_stream.xz";
            string outputDir = "output";
            string outputFilePath = Path.Combine(outputDir, "recovered.bin");
            string reportPath = Path.Combine(outputDir, "report.txt");

            // Validate input file existence
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputFilePath));

            // Decompress the XZ archive to a file
            using (XzArchive archive = new XzArchive(inputPath))
            {
                archive.Extract(outputFilePath);
            }

            // Get the size of the recovered data
            long byteCount = new FileInfo(outputFilePath).Length;

            // Write a text report with the recovered byte count
            using (StreamWriter writer = new StreamWriter(reportPath))
            {
                writer.WriteLine($"Recovered byte count: {byteCount}");
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

