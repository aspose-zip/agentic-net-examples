// HOW-TO: Generate SHAR Archive with Script Using Aspose.Zip in C# (Aspose.ZIP for .NET)
using System;
using System.IO;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Output SHAR archive path (hard‑coded)
            string outputPath = "script_with_comments.shar";

            // Ensure the output directory exists
            string outputDir = Path.GetDirectoryName(outputPath);
            Directory.CreateDirectory(outputDir ?? ".");

            // Content of the script file to be embedded in the SHAR archive
            string scriptContent = "#!/bin/sh\n" +
                                   "# This script demonstrates a simple SHAR archive with comments\n" +
                                   "# It prints a greeting message to the console\n" +
                                   "echo \"Hello, World!\"\n";

            // Build the SHAR archive text
            // A SHAR file is essentially a shell script that recreates the original files
            string sharContent = "#!/bin/sh\n" +
                                 "# SHAR archive generated by Aspose.Zip example\n" +
                                 "\n" +
                                 "cat > script.sh <<'END_OF_SCRIPT'\n" +
                                 scriptContent +
                                 "END_OF_SCRIPT\n" +
                                 "\n" +
                                 "chmod +x script.sh\n";

            // Write the SHAR archive to disk
            File.WriteAllText(outputPath, sharContent);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

