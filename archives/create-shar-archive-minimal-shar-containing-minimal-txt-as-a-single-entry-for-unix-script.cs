// HOW-TO: Create SHAR Archive From Text File Using C# (Aspose.ZIP for .NET)
using System;
using System.IO;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath = "minimal.txt";
            string outputPath = "minimal.shar";

            // Verify input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure output directory exists
            string outputDirectory = Path.GetDirectoryName(outputPath);
            if (string.IsNullOrEmpty(outputDirectory))
            {
                outputDirectory = ".";
            }
            Directory.CreateDirectory(outputDirectory);

            // Read the content of the input file
            string fileContent = File.ReadAllText(inputPath);

            // Create the SHAR script
            using (StreamWriter writer = new StreamWriter(outputPath, false, System.Text.Encoding.UTF8))
            {
                writer.WriteLine("#!/bin/sh");
                writer.WriteLine("# SHAR archive generated by Aspose.Zip example");
                writer.WriteLine($"cat > {Path.GetFileName(inputPath)} << 'EOF'");
                writer.WriteLine(fileContent);
                writer.WriteLine("EOF");
                writer.WriteLine($"chmod 644 {Path.GetFileName(inputPath)}");
            }

            Console.WriteLine($"SHAR archive created at: {outputPath}");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

