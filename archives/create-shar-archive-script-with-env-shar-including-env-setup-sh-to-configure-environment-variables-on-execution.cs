// HOW-TO: Generate SHAR Archive Including env_setup.sh Using C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Text;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath = "env_setup.sh";
            string outputPath = "script_with_env.shar";

            // Verify input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Create output directory unconditionally
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Read the environment setup script
            string envScript = File.ReadAllText(inputPath, Encoding.UTF8);

            // Build SHAR archive content
            StringBuilder sharBuilder = new StringBuilder();

            sharBuilder.AppendLine("#!/bin/sh");
            sharBuilder.AppendLine("# SHAR archive generated by Aspose.Zip example");
            sharBuilder.AppendLine();

            // Embed env_setup.sh within the SHAR
            sharBuilder.AppendLine("cat <<'EOF' > env_setup.sh");
            sharBuilder.AppendLine(envScript);
            sharBuilder.AppendLine("EOF");
            sharBuilder.AppendLine("chmod +x env_setup.sh");
            sharBuilder.AppendLine();

            // Example usage: source the environment script
            sharBuilder.AppendLine("echo \"Sourcing environment setup...\"");
            sharBuilder.AppendLine(". ./env_setup.sh");
            sharBuilder.AppendLine();

            sharBuilder.AppendLine("echo \"SHAR archive execution completed.\"");

            // Write the SHAR file
            File.WriteAllText(outputPath, sharBuilder.ToString(), Encoding.UTF8);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

