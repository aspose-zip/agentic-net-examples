// HOW-TO: Extract Specific File from CPIO Archive to Text File in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Linq;
using Aspose.Zip.Cpio;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded paths
            string inputPath = "archive.cpio";
            string outputPath = "extracted_entry.txt";
            // Name of the entry to extract
            string entryName = "desired_entry.txt";

            // Verify input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Open the CPIO archive
            using (CpioArchive archive = new CpioArchive(inputPath))
            {
                // Locate the specific entry
                var entry = archive.Entries.FirstOrDefault(e => e.Name == entryName);
                if (entry == null)
                {
                    Console.Error.WriteLine($"Entry not found: {entryName}");
                    return;
                }

                // Extract the entry to the output file
                using (FileStream outStream = new FileStream(outputPath, FileMode.Create, FileAccess.Write))
                {
                    entry.Extract(outStream);
                }
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

