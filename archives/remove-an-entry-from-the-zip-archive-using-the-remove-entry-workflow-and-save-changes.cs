// HOW-TO: Delete a File from a ZIP Archive Using Aspose.Zip in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Text;
using Aspose.Zip;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Define data directory
            string dataDir = "Data\\";
            Directory.CreateDirectory(dataDir);

            // Create a sample ZIP archive
            CompressMultipleFiles.Run();

            // Path to the source archive
            string sourceArchivePath = dataDir + "sample.zip";
            if (!File.Exists(sourceArchivePath))
            {
                Console.Error.WriteLine($"File not found: {sourceArchivePath}");
                return;
            }

            // Open the archive and delete the first entry
            using (Archive archive = new Archive(sourceArchivePath))
            {
                if (archive.Entries.Count > 0)
                {
                    ArchiveEntry firstEntry = archive.Entries[0];
                    archive.DeleteEntry(firstEntry);
                }

                // Save the modified archive
                string resultPath = dataDir + "sample_modified.zip";
                Directory.CreateDirectory(Path.GetDirectoryName(resultPath));
                archive.Save(resultPath);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

static class CompressMultipleFiles
{
    public static void Run()
    {
        string dataDir = "Data\\";
        Directory.CreateDirectory(dataDir);
        string archivePath = dataDir + "sample.zip";

        using (Archive archive = new Archive())
        {
            // Create first entry
            MemoryStream ms1 = new MemoryStream(Encoding.UTF8.GetBytes("Hello World"));
            archive.CreateEntry("file1.txt", ms1);

            // Create second entry
            MemoryStream ms2 = new MemoryStream(Encoding.UTF8.GetBytes("Another file"));
            archive.CreateEntry("file2.txt", ms2);

            // Ensure output directory exists and save the archive
            Directory.CreateDirectory(Path.GetDirectoryName(archivePath));
            archive.Save(archivePath);
        }
    }
}

