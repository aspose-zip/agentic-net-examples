// HOW-TO: Extract All Files From a CAB Archive to a Folder in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Cab;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath = "input.cab";
            string outputPath = "CabEntriesOutput\\";

            // Verify input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure the base output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Load the CAB archive
            using (CabArchive archive = new CabArchive(inputPath))
            {
                // Iterate over entries and extract each one
                foreach (var entry in archive.Entries)
                {
                    string entryOutputPath = Path.Combine(outputPath, entry.Name);

                    // Ensure directory for the entry exists
                    Directory.CreateDirectory(Path.GetDirectoryName(entryOutputPath));

                    using (FileStream fs = new FileStream(entryOutputPath, FileMode.Create, FileAccess.Write))
                    {
                        entry.Extract(fs);
                    }
                }
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

