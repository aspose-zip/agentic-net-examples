// HOW-TO: Create SHAR Archive with Executable and Text Files in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Text;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            string inputExe = "app.exe";
            string inputReadme = "readme.md";
            string inputLicense = "license.txt";
            string outputShar = "deployment.shar";

            if (!File.Exists(inputExe))
            {
                Console.Error.WriteLine($"File not found: {inputExe}");
                return;
            }
            if (!File.Exists(inputReadme))
            {
                Console.Error.WriteLine($"File not found: {inputReadme}");
                return;
            }
            if (!File.Exists(inputLicense))
            {
                Console.Error.WriteLine($"File not found: {inputLicense}");
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(outputShar) ?? string.Empty);

            using (StreamWriter writer = new StreamWriter(outputShar, false, Encoding.UTF8))
            {
                writer.WriteLine("#!/bin/sh");
                writer.WriteLine("# SHAR archive generated by Aspose.Zip example");

                // app.exe (binary) - base64 decode
                writer.WriteLine($"echo \"Extracting {inputExe}\"");
                writer.WriteLine($"base64 -d <<'EOF' > {inputExe}");
                string exeBase64 = Convert.ToBase64String(File.ReadAllBytes(inputExe));
                for (int i = 0; i < exeBase64.Length; i += 76)
                {
                    writer.WriteLine(exeBase64.Substring(i, Math.Min(76, exeBase64.Length - i)));
                }
                writer.WriteLine("EOF");

                // readme.md (text)
                writer.WriteLine($"cat <<'EOF' > {inputReadme}");
                writer.WriteLine(File.ReadAllText(inputReadme));
                writer.WriteLine("EOF");

                // license.txt (text)
                writer.WriteLine($"cat <<'EOF' > {inputLicense}");
                writer.WriteLine(File.ReadAllText(inputLicense));
                writer.WriteLine("EOF");

                writer.WriteLine("echo \"Extraction complete.\"");
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

