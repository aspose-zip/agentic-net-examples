// HOW-TO: Create SHAR Archive with Install and Cleanup Scripts in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Text;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            string installPath = "install.sh";
            string cleanupPath = "cleanup.sh";
            string outputPath = "scripts.shar";

            if (!File.Exists(installPath))
            {
                Console.Error.WriteLine($"File not found: {installPath}");
                return;
            }

            if (!File.Exists(cleanupPath))
            {
                Console.Error.WriteLine($"File not found: {cleanupPath}");
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(outputPath) ?? ".");

            string installContent;
            using (StreamReader reader = new StreamReader(installPath))
            {
                installContent = reader.ReadToEnd();
            }

            string cleanupContent;
            using (StreamReader reader = new StreamReader(cleanupPath))
            {
                cleanupContent = reader.ReadToEnd();
            }

            StringBuilder sharBuilder = new StringBuilder();
            sharBuilder.AppendLine("#!/bin/sh");
            sharBuilder.AppendLine("# SHAR archive generated by Aspose.Zip example");
            sharBuilder.AppendLine("cat >install.sh <<'EOF'");
            sharBuilder.AppendLine(installContent);
            sharBuilder.AppendLine("EOF");
            sharBuilder.AppendLine("chmod +x install.sh");
            sharBuilder.AppendLine("cat >cleanup.sh <<'EOF'");
            sharBuilder.AppendLine(cleanupContent);
            sharBuilder.AppendLine("EOF");
            sharBuilder.AppendLine("chmod +x cleanup.sh");
            sharBuilder.AppendLine("echo \"Installation and cleanup scripts extracted.\"");

            using (StreamWriter writer = new StreamWriter(outputPath, false, Encoding.UTF8))
            {
                writer.Write(sharBuilder.ToString());
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

