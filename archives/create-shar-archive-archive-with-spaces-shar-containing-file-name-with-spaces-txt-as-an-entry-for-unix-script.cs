// HOW-TO: Create SHAR Archive With File Name Containing Spaces In C# (Aspose.ZIP for .NET)
using System;
using System.IO;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath = "input.txt";
            string outputPath = "archive_with_spaces.shar";

            // Verify input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Read the content of the input file
            string fileContent = File.ReadAllText(inputPath);

            // Build the SHAR script content
            string sharContent = "#!/bin/sh\n" +
                                 "# SHAR archive generated by Aspose.Zip example\n" +
                                 "cat <<'EOF' > \"file name with spaces.txt\"\n" +
                                 fileContent + "\n" +
                                 "EOF\n";

            // Write the SHAR archive to the output file
            File.WriteAllText(outputPath, sharContent);
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

