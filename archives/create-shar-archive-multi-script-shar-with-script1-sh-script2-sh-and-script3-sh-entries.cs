// HOW-TO: Create SHAR Archive From Multiple Shell Scripts In C# (Aspose.ZIP for .NET)
using System;
using System.IO;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input and output paths
            string inputPath1 = "script1.sh";
            string inputPath2 = "script2.sh";
            string inputPath3 = "script3.sh";
            string outputPath = "multi_script.shar";

            // Validate input files
            if (!File.Exists(inputPath1))
            {
                Console.Error.WriteLine($"File not found: {inputPath1}");
                return;
            }
            if (!File.Exists(inputPath2))
            {
                Console.Error.WriteLine($"File not found: {inputPath2}");
                return;
            }
            if (!File.Exists(inputPath3))
            {
                Console.Error.WriteLine($"File not found: {inputPath3}");
                return;
            }

            // Ensure output directory exists
            string outputDir = Path.GetDirectoryName(outputPath);
            Directory.CreateDirectory(string.IsNullOrEmpty(outputDir) ? "." : outputDir);

            // Create SHAR archive by concatenating scripts
            using (FileStream outputStream = new FileStream(outputPath, FileMode.Create, FileAccess.Write))
            using (StreamWriter writer = new StreamWriter(outputStream))
            {
                // Optional SHAR header
                writer.WriteLine("#!/bin/sh");
                writer.WriteLine("# SHAR archive generated by Aspose.Zip example");
                writer.WriteLine();

                // Append script1.sh
                writer.WriteLine("# Begin script1.sh");
                string content1 = File.ReadAllText(inputPath1);
                writer.WriteLine(content1);
                writer.WriteLine("# End script1.sh");
                writer.WriteLine();

                // Append script2.sh
                writer.WriteLine("# Begin script2.sh");
                string content2 = File.ReadAllText(inputPath2);
                writer.WriteLine(content2);
                writer.WriteLine("# End script2.sh");
                writer.WriteLine();

                // Append script3.sh
                writer.WriteLine("# Begin script3.sh");
                string content3 = File.ReadAllText(inputPath3);
                writer.WriteLine(content3);
                writer.WriteLine("# End script3.sh");
                writer.WriteLine();
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

