// HOW-TO: Create 7z Archive with 64 MB LZMA Dictionary in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.SevenZip;
using Aspose.Zip.Saving;

class Program
{
    static void Main(string[] args)
    {
        // Hardcoded input directory and output archive path
        string inputDir = @"C:\InputFolder";
        string outputPath = @"C:\Output\archive.7z";

        // Verify input directory exists
        if (!Directory.Exists(inputDir))
        {
            Console.Error.WriteLine($"Directory not found: {inputDir}");
            return;
        }

        // Ensure output directory exists
        Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

        try
        {
            // Configure LZMA compression with a 64 MB dictionary size
            SevenZipLZMACompressionSettings lzmaSettings = new SevenZipLZMACompressionSettings();
            lzmaSettings.DictionarySize = 64 * 1024 * 1024; // 64 MB

            // Create entry settings using the LZMA compression settings
            SevenZipEntrySettings entrySettings = new SevenZipEntrySettings(lzmaSettings);

            // Create the 7z archive with the specified entry settings
            using (SevenZipArchive archive = new SevenZipArchive(entrySettings))
            {
                // Add all files from the input directory
                archive.CreateEntries(inputDir);

                // Save the archive to the output path
                archive.Save(outputPath);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

