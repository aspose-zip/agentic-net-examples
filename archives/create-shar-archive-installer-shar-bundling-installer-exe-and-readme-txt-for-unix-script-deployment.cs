// HOW-TO: Create SHAR Archive With Embedded EXE And README Using C# (Aspose.ZIP for .NET)
using System;
using System.IO;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            string inputExePath = "installer.exe";
            string inputReadmePath = "README.txt";
            string outputSharPath = "installer.shar";

            if (!File.Exists(inputExePath))
            {
                Console.Error.WriteLine($"File not found: {inputExePath}");
                return;
            }

            if (!File.Exists(inputReadmePath))
            {
                Console.Error.WriteLine($"File not found: {inputReadmePath}");
                return;
            }

            string outputDirectory = Path.GetDirectoryName(outputSharPath);
            if (string.IsNullOrEmpty(outputDirectory))
            {
                outputDirectory = ".";
            }
            Directory.CreateDirectory(outputDirectory);

            using (StreamWriter writer = new StreamWriter(outputSharPath, false, System.Text.Encoding.UTF8))
            {
                writer.WriteLine("#!/bin/sh");
                writer.WriteLine("# SHAR archive generated by Aspose.Zip example");
                writer.WriteLine();

                // Embed installer.exe
                writer.WriteLine("echo \"Extracting installer.exe...\"");
                writer.WriteLine("base64 -d <<'EOF' > installer.exe");
                string exeBase64 = Convert.ToBase64String(File.ReadAllBytes(inputExePath));
                for (int i = 0; i < exeBase64.Length; i += 76)
                {
                    int length = Math.Min(76, exeBase64.Length - i);
                    writer.WriteLine(exeBase64.Substring(i, length));
                }
                writer.WriteLine("EOF");
                writer.WriteLine();

                // Embed README.txt
                writer.WriteLine("echo \"Extracting README.txt...\"");
                writer.WriteLine("base64 -d <<'EOF' > README.txt");
                string readmeBase64 = Convert.ToBase64String(File.ReadAllBytes(inputReadmePath));
                for (int i = 0; i < readmeBase64.Length; i += 76)
                {
                    int length = Math.Min(76, readmeBase64.Length - i);
                    writer.WriteLine(readmeBase64.Substring(i, length));
                }
                writer.WriteLine("EOF");
                writer.WriteLine();

                writer.WriteLine("echo \"Extraction complete.\"");
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

