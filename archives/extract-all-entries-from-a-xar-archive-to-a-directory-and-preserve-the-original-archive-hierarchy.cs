// HOW-TO: Extract All Files from XAR Archive Preserving Folder Structure in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Xar;

class Program
{
    static void Main(string[] args)
    {
        // Hardcoded input XAR archive path and output directory path
        string inputPath = "sample.xar";
        string outputPath = "ExtractedFiles";

        try
        {
            // Verify that the input archive exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure the output directory exists (creates it if necessary)
            Directory.CreateDirectory(outputPath);

            // Open the XAR archive for reading
            using (FileStream fs = File.OpenRead(inputPath))
            {
                // Initialize the XarArchive with the opened stream
                using (XarArchive archive = new XarArchive(fs))
                {
                    // Extract all entries preserving the original hierarchy
                    archive.ExtractToDirectory(outputPath);
                }
            }
        }
        catch (Exception ex)
        {
            // Output any unexpected errors
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

