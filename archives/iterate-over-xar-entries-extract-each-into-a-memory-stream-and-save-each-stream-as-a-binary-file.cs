// HOW-TO: Extract All Files From XAR Archive To Directory Using C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Xar;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            string inputPath = "input.xar";
            string outputDir = "extracted";

            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            Directory.CreateDirectory(outputDir);

            using (XarArchive archive = new XarArchive(File.OpenRead(inputPath)))
            {
                archive.ExtractToDirectory(outputDir);
            }

            Console.WriteLine("Extraction completed.");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

