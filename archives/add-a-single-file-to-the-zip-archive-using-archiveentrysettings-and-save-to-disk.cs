// HOW-TO: Add a Single File to a ZIP Archive with Aspose.Zip in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip;
using Aspose.Zip.Saving;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded paths
            string dataDir = "C:\\Data\\";
            string sourceFilePath = dataDir + "example.txt";
            string outputZipPath = dataDir + "output.zip";

            // Validate input file exists
            if (!File.Exists(sourceFilePath))
            {
                Console.Error.WriteLine($"File not found: {sourceFilePath}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputZipPath));

            // Create a file stream for the output ZIP archive
            using (FileStream zipStream = File.Open(outputZipPath, FileMode.Create))
            {
                // Initialize Archive with default entry settings
                using (Archive archive = new Archive(new ArchiveEntrySettings()))
                {
                    // Add the single file to the archive; entry name is the file name
                    archive.CreateEntry(Path.GetFileName(sourceFilePath), sourceFilePath);

                    // Save the archive to the output stream
                    archive.Save(zipStream);
                }
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

