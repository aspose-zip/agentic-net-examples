// HOW-TO: Extract v7 Header TAR Archive to Folder Using Aspose.Zip in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Tar;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input TAR file and output directory
            string inputPath = "input.tar";
            string outputPath = "output";

            // Verify the input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure the output directory's parent exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Open the TAR archive and extract its contents using automatic variant processing
            using (TarArchive archive = new TarArchive(inputPath))
            {
                archive.ExtractToDirectory(outputPath);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

