// HOW-TO: Create SHAR Archive with Image Audio and Video Files in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Text;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            string inputImage = "image.png";
            string inputAudio = "audio.mp3";
            string inputVideo = "video.mp4";
            string outputShar = "multi_type.shar";

            if (!File.Exists(inputImage))
            {
                Console.Error.WriteLine($"File not found: {inputImage}");
                return;
            }
            if (!File.Exists(inputAudio))
            {
                Console.Error.WriteLine($"File not found: {inputAudio}");
                return;
            }
            if (!File.Exists(inputVideo))
            {
                Console.Error.WriteLine($"File not found: {inputVideo}");
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(outputShar) ?? string.Empty);

            using (StreamWriter writer = new StreamWriter(outputShar, false, Encoding.UTF8))
            {
                writer.WriteLine("#!/bin/sh");
                writer.WriteLine("# SHAR archive generated by Aspose.Zip example");
                writer.WriteLine();

                // Image entry
                byte[] imageBytes = File.ReadAllBytes(inputImage);
                string imageBase64 = Convert.ToBase64String(imageBytes);
                writer.WriteLine($"echo \"{imageBase64}\" | base64 -d > {Path.GetFileName(inputImage)}");
                writer.WriteLine();

                // Audio entry
                byte[] audioBytes = File.ReadAllBytes(inputAudio);
                string audioBase64 = Convert.ToBase64String(audioBytes);
                writer.WriteLine($"echo \"{audioBase64}\" | base64 -d > {Path.GetFileName(inputAudio)}");
                writer.WriteLine();

                // Video entry
                byte[] videoBytes = File.ReadAllBytes(inputVideo);
                string videoBase64 = Convert.ToBase64String(videoBytes);
                writer.WriteLine($"echo \"{videoBase64}\" | base64 -d > {Path.GetFileName(inputVideo)}");
                writer.WriteLine();

                writer.WriteLine("echo \"Extraction complete.\"");
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

