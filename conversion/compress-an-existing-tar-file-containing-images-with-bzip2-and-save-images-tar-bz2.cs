// HOW-TO: Compress an Images TAR Archive to BZIP2 in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip.Bzip2;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Hardcoded input TAR file containing images
            string inputPath = @"C:\Data\images.tar";
            // Desired output BZIP2 compressed TAR file
            string outputPath = @"C:\Data\images.tar.bz2";

            // Verify that the input file exists
            if (!File.Exists(inputPath))
            {
                Console.Error.WriteLine($"File not found: {inputPath}");
                return;
            }

            // Ensure the output directory exists
            Directory.CreateDirectory(Path.GetDirectoryName(outputPath));

            // Compress the TAR archive using BZIP2
            using (Bzip2Archive bz2 = new Bzip2Archive())
            {
                bz2.SetSource(inputPath);
                bz2.Save(outputPath);
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

