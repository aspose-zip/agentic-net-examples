// HOW-TO: Create Split ZIP Archive of Markdown Files with 64KB Segments in C# (Aspose.ZIP for .NET)
using System;
using System.IO;
using Aspose.Zip;
using Aspose.Zip.Saving;

class Program
{
    static void Main(string[] args)
    {
        try
        {
            // Define input directory containing markdown files
            string inputDirectory = "Data";
            // Define output directory for split archive segments
            string outputDirectory = "Output";

            // Verify input directory exists
            if (!Directory.Exists(inputDirectory))
            {
                Console.Error.WriteLine($"Directory not found: {inputDirectory}");
                return;
            }

            // Ensure output directory exists
            Directory.CreateDirectory(outputDirectory);

            // Create a new ZIP archive
            using (Archive archive = new Archive())
            {
                // Get all markdown files in the input directory
                string[] markdownFiles = Directory.GetFiles(inputDirectory, "*.md", SearchOption.TopDirectoryOnly);
                foreach (string filePath in markdownFiles)
                {
                    // Verify the file exists
                    if (!File.Exists(filePath))
                    {
                        Console.Error.WriteLine($"File not found: {filePath}");
                        continue;
                    }

                    // Use the file name as the entry name inside the archive
                    string entryName = Path.GetFileName(filePath);
                    // Add the file to the archive
                    archive.CreateEntry(entryName, new FileInfo(filePath));
                }

                // Configure split (multivolume) options: 64 KiB per segment, base name "md"
                SplitArchiveSaveOptions saveOptions = new SplitArchiveSaveOptions("md", 65536);

                // Save the archive as split segments in the output directory
                archive.SaveSplit(outputDirectory, saveOptions);
            }

            Console.WriteLine("Multivolume ZIP archive created successfully.");
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

