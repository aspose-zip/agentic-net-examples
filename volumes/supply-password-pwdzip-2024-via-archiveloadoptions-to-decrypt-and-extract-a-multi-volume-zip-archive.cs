// HOW-TO: Extract Encrypted Multi‑Volume ZIP Archive In C# With Aspose.Zip (Aspose.ZIP for .NET)
using System;
using System.IO;
using System.Linq;
using Aspose.Zip;

public class Program
{
    public static void Main(string[] args)
    {
        try
        {
            // Hardcoded paths
            string dataDir = @"C:\Data\MultivolumeZip";
            string outputDir = Path.Combine(dataDir, "Extracted");

            // Ensure output directory exists
            Directory.CreateDirectory(outputDir);

            // Main segment of the multivolume ZIP
            string mainSegment = Path.Combine(dataDir, "archive.zip");
            if (!File.Exists(mainSegment))
            {
                Console.Error.WriteLine($"File not found: {mainSegment}");
                return;
            }

            // Collect split segment files (exclude the main segment)
            string[] segmentFiles = Directory.GetFiles(dataDir, "archive.zip.*")
                .Where(f => !f.Equals(mainSegment, StringComparison.OrdinalIgnoreCase))
                .OrderBy(f => f)
                .ToArray();

            // Verify each split segment exists
            foreach (string seg in segmentFiles)
            {
                if (!File.Exists(seg))
                {
                    Console.Error.WriteLine($"File not found: {seg}");
                    return;
                }
            }

            // Load the multivolume archive with the password
            ArchiveLoadOptions loadOptions = new ArchiveLoadOptions();
            loadOptions.DecryptionPassword = "PwdZip#2024";

            using (Archive archive = new Archive(mainSegment, segmentFiles, loadOptions))
            {
                foreach (ArchiveEntry entry in archive.Entries)
                {
                    string outPath = Path.Combine(outputDir, entry.Name);

                    // Create directory for entry if it is a folder
                    if (entry.IsDirectory)
                    {
                        Directory.CreateDirectory(outPath);
                        continue;
                    }

                    // Ensure the directory for the file exists
                    Directory.CreateDirectory(Path.GetDirectoryName(outPath));

                    using (FileStream output = new FileStream(outPath, FileMode.Create, FileAccess.Write))
                    {
                        entry.Extract(output);
                    }
                }
            }
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"Error: {ex.Message}");
        }
    }
}

